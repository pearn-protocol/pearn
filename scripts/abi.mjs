// Writes apps/web/lib/abi.ts from the compiled contracts, so the app's ABI cannot drift.
// Usage: pnpm abi (needs forge). CI regenerates it and fails on a diff; Biome skips the file.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const CONTRACTS = { pearnMarketsAbi: "PearnMarkets", rateOracleAbi: "StNearRateOracle" };
const cwd = new URL("../contracts/", import.meta.url);

const body = Object.entries(CONTRACTS)
	.map(([name, contract]) => {
		const abi = execFileSync("forge", ["inspect", contract, "abi", "--json"], { cwd });
		return `export const ${name} = ${JSON.stringify(JSON.parse(abi), null, "\t")} as const;\n`;
	})
	.join("\n");

const out = new URL("../apps/web/lib/abi.ts", import.meta.url);
writeFileSync(out, `// Generated by scripts/abi.mjs from contracts/. Do not edit.\n\n${body}`);
